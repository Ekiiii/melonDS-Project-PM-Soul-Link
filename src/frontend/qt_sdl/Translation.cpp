MelonTranslator& MelonTranslator::Instance()
{
    static MelonTranslator s_instance;
    return s_instance;
}

MelonTranslator::MelonTranslator(QObject* parent)
    : QTranslator(parent), currentLang("en")
{
}

void MelonTranslator::Init(QCoreApplication* app)
{
    MelonTranslator& inst = Instance();
    Config::Table cfg = Config::GetGlobalTable();
    inst.currentLang = cfg.GetQString("UI.Language");
    if (inst.currentLang != "fr" && inst.currentLang != "en") inst.currentLang = "en";
    if (app) app->installTranslator(&inst);
}

void MelonTranslator::SetLanguage(const QString& lang)
{
    Instance().currentLang = (lang == "fr") ? "fr" : "en";
}

QString MelonTranslator::GetLanguage()
{
    return Instance().currentLang;
}

QString MelonTranslator::Tr(const QString& text)
{
    if (Instance().currentLang != "fr") return text;
    std::string s = text.toStdString();
    auto it = s_FrenchDict.find(s);
    if (it != s_FrenchDict.end())
        return QString::fromUtf8(it->second);
    return text;
}

const char* MelonTranslator::TrC(const char* text)
{
    if (Instance().currentLang != "fr" || !text) return text;
    auto it = s_FrenchDict.find(text);
    if (it != s_FrenchDict.end())
        return it->second;
    return text;
}

QString MelonTranslator::translate(const char *context, const char *sourceText,
                                  const char *disambiguation, int n) const
{
    if (currentLang != "fr" || !sourceText || !sourceText[0])
        return QString();

    auto it = s_FrenchDict.find(sourceText);
    if (it != s_FrenchDict.end())
    {
        return QString::fromUtf8(it->second);
    }
    return QString();
}
